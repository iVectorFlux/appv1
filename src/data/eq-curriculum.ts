export function applyDatabaseCompetencyGuides(guides: CompetencyReadingGuide[]): void {
  for (const guide of guides) {
    const key = guide.key.trim().toUpperCase().replace(/[\s-]+/g, '_');
    if (!key) continue;
    const existing = EQ_COMPETENCY_CURRICULUM[key];
    EQ_COMPETENCY_CURRICULUM[key] = {
      ...(existing ?? guide),
      ...guide,
      key,
      howToMeasure:
        Array.isArray(guide.howToMeasure) && guide.howToMeasure.length > 0
          ? guide.howToMeasure
          : existing?.howToMeasure ?? [],
    };
  }
}

